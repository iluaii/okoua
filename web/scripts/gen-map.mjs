// Generates SVG paths for the oblasts from data/geo/ukr-adm1.geojson into src/lib/map/regions.ts.
// Projection: Lambert conformal conic (as on familiar maps of Ukraine); simplification keeps shared borders.
// OSM oblast boundaries include 12-mile territorial waters (hence circles around capes and Zmiinyi Island),
// so oblasts are clipped to land from Natural Earth.

import { readFile, writeFile } from 'node:fs/promises';
import mapshaper from 'mapshaper';

const SRC = new URL('../../data/geo/ukr-adm1.geojson', import.meta.url);
const LAND = new URL('../../data/geo/land-ukr.geojson', import.meta.url);
const OUT = new URL('../src/lib/map/regions.ts', import.meta.url);
const WIDTH = 1000;
const PAD = 6;

// ISO 3166-2 → UID and name from alerts.in.ua.
const REGIONS = {
	'UA-68': [3, 'Хмельницька область'],
	'UA-05': [4, 'Вінницька область'],
	'UA-56': [5, 'Рівненська область'],
	'UA-07': [8, 'Волинська область'],
	'UA-12': [9, 'Дніпропетровська область'],
	'UA-18': [10, 'Житомирська область'],
	'UA-21': [11, 'Закарпатська область'],
	'UA-23': [12, 'Запорізька область'],
	'UA-26': [13, 'Івано-Франківська область'],
	'UA-32': [14, 'Київська область'],
	'UA-35': [15, 'Кіровоградська область'],
	'UA-09': [16, 'Луганська область'],
	'UA-48': [17, 'Миколаївська область'],
	'UA-51': [18, 'Одеська область'],
	'UA-53': [19, 'Полтавська область'],
	'UA-59': [20, 'Сумська область'],
	'UA-61': [21, 'Тернопільська область'],
	'UA-63': [22, 'Харківська область'],
	'UA-65': [23, 'Херсонська область'],
	'UA-71': [24, 'Черкаська область'],
	'UA-74': [25, 'Чернігівська область'],
	'UA-77': [26, 'Чернівецька область'],
	'UA-46': [27, 'Львівська область'],
	'UA-14': [28, 'Донецька область'],
	'UA-43': [29, 'Автономна Республіка Крим'],
	'UA-40': [30, 'м. Севастополь'],
	'UA-30': [31, 'м. Київ']
};
// Cities are drawn on top of the oblasts around them.
const ON_TOP = new Set([30, 31]);

const input = await readFile(SRC, 'utf8');
const land = await readFile(LAND, 'utf8');
const out = await mapshaper.applyCommands(
	[
		'-i in.json',
		'-clip land.json',
		// Clipping leaves tiny slivers along the coast.
		'-filter-slivers min-area=2km2',
		'-proj +proj=lcc +lat_1=45 +lat_2=50 +lat_0=48 +lon_0=31 +datum=WGS84',
		'-simplify 15% keep-shapes',
		"-each 'cx=this.innerX, cy=this.innerY'",
		'-o out.json format=geojson'
	].join(' '),
	{ 'in.json': input, 'land.json': land }
);
const fc = JSON.parse(out['out.json']);

const rings = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates).flat();
let [x0, y0, x1, y1] = [Infinity, Infinity, -Infinity, -Infinity];
for (const f of fc.features) {
	for (const [x, y] of rings(f.geometry).flat()) {
		x0 = Math.min(x0, x);
		x1 = Math.max(x1, x);
		y0 = Math.min(y0, y);
		y1 = Math.max(y1, y);
	}
}
const k = (WIDTH - 2 * PAD) / (x1 - x0);
const height = Math.ceil((y1 - y0) * k + 2 * PAD);
const px = (x) => +((x - x0) * k + PAD).toFixed(1);
const py = (y) => +((y1 - y) * k + PAD).toFixed(1);

const regions = fc.features.map((f) => {
	const iso = f.properties.shapeISO;
	const known = REGIONS[iso];
	if (!known) throw new Error(`unknown region ${iso}`);
	const d = rings(f.geometry)
		.map((ring) => 'M' + ring.map(([x, y]) => `${px(x)} ${py(y)}`).join('L') + 'Z')
		.join('');
	return { uid: known[0], name: known[1], d, cx: px(f.properties.cx), cy: py(f.properties.cy) };
});
if (regions.length !== Object.keys(REGIONS).length) throw new Error(`got ${regions.length} regions`);
regions.sort((a, b) => Number(ON_TOP.has(a.uid)) - Number(ON_TOP.has(b.uid)) || a.uid - b.uid);

const ts = `// SPDX-License-Identifier: AGPL-3.0-or-later
// Generated by scripts/gen-map.mjs, do not edit by hand.
// Boundaries: © OpenStreetMap contributors (ODbL), via geoBoundaries.

export interface MapRegion {
	uid: number;
	name: string;
	d: string;
	/** A point inside the region, for a label. */
	cx: number;
	cy: number;
}

export const viewBox = '0 0 ${WIDTH} ${height}';

export const regions: MapRegion[] = ${JSON.stringify(regions, null, '\t')};
`;
await writeFile(OUT, ts);
console.log(`regions.ts: ${regions.length} regions, ${(ts.length / 1024).toFixed(0)} KB, viewBox 0 0 ${WIDTH} ${height}`);
